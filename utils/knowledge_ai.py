async def _call_gemini_api(prompt: str) -> str:
    """Call Google Gemini API with fallback across popular free flash models."""
    api_key = config.GEMINI_API_KEY
    if not api_key:
        return ""

    models_to_try = ["gemini-1.5-flash", "gemini-2.0-flash", "gemini-2.5-flash"]

    payload = {
        "system_instruction": {
            "parts": [{"text": SYSTEM_PROMPT}]
        },
        "contents": [
            {"role": "user", "parts": [{"text": prompt}]}
        ],
        "generationConfig": {
            "temperature": 0.7,
            "maxOutputTokens": 1024,
        }
    }

    async with httpx.AsyncClient(timeout=30.0) as client:
        for model in models_to_try:
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"
            try:
                response = await client.post(url, json=payload)
                if response.status_code == 200:
                    data = response.json()
                    text = data["candidates"][0]["content"]["parts"][0]["text"]
                    if text:
                        return text.strip()
            except Exception as e:
                logger.warning(f"Error calling {model}: {e}")

    return ""

async def _call_openai_api(prompt: str) -> str:
    """Call OpenAI API if key is provided."""
    api_key = config.OPENAI_API_KEY
    if not api_key:
        return ""

    url = "https://api.openai.com/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
    }
    payload = {
        "model": "gpt-4o-mini",
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": prompt}
        ],
        "temperature": 0.7,
        "max_tokens": 1000,
    }

    try:
        async with httpx.AsyncClient(timeout=30.0) as client:
            response = await client.post(url, headers=headers, json=payload)
            if response.status_code == 200:
                data = response.json()
                text = data["choices"][0]["message"]["content"]
                return text.strip()
            else:
                logger.warning(f"OpenAI API returned status {response.status_code}: {response.text}")
    except Exception as e:
        logger.error(f"Error calling OpenAI API: {e}")

    return ""

